function opps(c: Case) {
	return c.steps.flatMap((s) =>
		s.type === "opportunity" && s.expect ? [s] : [],
	);
}
function count(cs: Case[]) {
	let total = 0;
	let needed = 0;
	for (const c of cs)
		for (const o of opps(c)) {
			total += 1;
			if (o.expect!.needed) needed += 1;
		}
	return { total, needed, not: total - needed };
}
function expectCell(c: Case): string {
	return opps(c)
		.map((o) => {
			const e = o.expect!;
			if (e.needed) {
				const acts = e.accept.join("/");
				return `${o.id}: ${acts}（根拠 ${e.evidenceAny.join(",")}）`;
			}
			const w = e.accept.length === 3 ? "wait系" : e.accept.join("/");
			return `${o.id}: ${w}（${e.failureIfOutward}）`;
		})
		.join("<br>");
}
function seeCell(c: Case): string {
	const first = c.description.split("。")[0] ?? c.description;
	return `${first}。`;
}
function rows(cs: Case[]): string {
	return cs
		.map(
			(c) =>
				`| ${c.id} | ${c.title.replace(/\|/g, "/")} | ${seeCell(c).replace(/\|/g, "/")} | ${expectCell(c)} |`,
		)
		.join("\n");
}
function countRows(cs: Case[]): string {
	return groups
		.map((g) => {
			const sub = cs.filter((c) => c.group === g);
			const n = count(sub);
			return `| ${g} | ${sub.length} | ${n.total} | ${n.needed} | ${n.not} |`;
		})
		.join("\n");
}
const cd = count(dev);
const cu = count(unseen);
const ca = count(all);
const pct = (x: { total: number; needed: number }) =>
	`${Math.round((100 * x.needed) / x.total)}%`;

