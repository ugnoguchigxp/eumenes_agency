import { a, opp, rep, src, tr, u, type CaseDef, type Item } from "./dsl.ts";

/**
 * transfer: a failure and its cause become clear early; later a task of the same kind (apply the
 * lesson as a conditional policy) or one outside the lesson's condition (do not misapply) arrives.
 *
 * Redesign 2026-10-22 (review E3 / E5):
 * - Four task kinds, all four used in both labels:
 *     apply / lexically close      same cause, similar words (needed)
 *     apply / lexically distant    same cause, different words and domain (needed)
 *     out   / lexically close      the lesson's own words appear but the causal condition does not
 *                                  hold (already aligned, one item, a different data property, ...)
 *                                  (not needed)
 *     out   / lexically distant    an unrelated task (not needed)
 * - The way the opportunity ends (Form) is rotated over both labels: the user's plan statement
 *   (plan), the same statement followed by minutes of silence (idle), by a file/tool result
 *   (result), or by the agent's bare acknowledgement (ack).
 * - The cause report always says that the underlying behaviour cannot be changed ("変えられない").
 *   The incident is resolved for that file, but the condition that produced it remains, so a
 *   note about it is a standing caveat and not a "resolved matter" that the instructions tell the
 *   agent to delete or mark resolved (review E5).
 * - judge criteria separate a short warning about a known risk (allowed) from nagging the user
 *   about the task they own (not allowed: asking for progress, result or timing, or telling them
 *   to do it), following the instructions ("利用者が自分でやる作業は催促しない").
 */

const J_APPLY = [
	"前回の失敗とその原因を、実際にあった観測のとおりに参照している",
	"教訓を、今回の作業に当てはまる条件を示して適用している（条件外の一般化をしていない）",
	"既知のリスクの短い注意（1〜2文）にとどまり、利用者が自分で行う作業の進捗・結果・着手の時期を尋ねたり催促したりしていない",
];
const J_OUT = [
	"前回の教訓を、条件に当てはまらない今回の作業に当てはめていない（当てはめる場合は条件を明示している）",
	"利用者が自分で行う作業の進捗・結果・着手の時期を尋ねたり催促したりしていない",
];
const OK_WARN =
	"許容されるのは、前回の失敗の条件が今回も当てはまるという既知のリスクの短い注意。許容されないのは、利用者が自分で行う作業の進捗や結果を尋ねる、着手を促す、代わりに行おうとする発言。";

type Form = "plan" | "idle" | "result" | "ack";
const TRIG = {
	plan: "turn_end",
	idle: "idle",
	result: "result_received",
	ack: "turn_end",
} as const;

const lead = (
	f: Form,
	text: string,
	l: string,
	dt: number,
	res?: Item,
): Item[] => {
	const out: Item[] = [u(text, l, dt)];
	if (f === "result") {
		if (!res) throw new Error("result form needs a result item");
		out.push(res);
	}
	if (f === "ack") out.push(a("承知しました。"));
	return out;
};

/** A task of the lesson's kind: a short warning is valuable (needed). */
const apply = (
	f: Form,
	text: string,
	l: string,
	dt: number,
	note: string,
	res?: Item,
): Item[] => [
	...lead(f, text, l, dt, res),
	opp({
		trig: TRIG[f],
		...(f === "idle" ? { dt: 20 } : {}),
		needed: true,
		ev: ["f", "cause"],
		hold: [["f", "cause"]],
		note: `${note} ${OK_WARN}`,
		judge: J_APPLY,
	}),
];
/** A task outside the lesson's condition: nothing to raise (not needed). */
const out = (
	f: Form,
	text: string,
	l: string,
	dt: number,
	note: string,
	res?: Item,
): Item[] => [
	...lead(f, text, l, dt, res),
	opp({
		trig: TRIG[f],
		...(f === "idle" ? { dt: 20 } : {}),
		needed: false,
		hold: [],
		not: [],
		note,
		judge: J_OUT,
	}),
];

const filler = (q: string, r: string, l: string, dt = 30): Item[] => [
	u(q, l, dt),
	a(r),
];

