import { a, opp, rep, tr, u, type CaseDef, type Item } from "./dsl.ts";

/**
 * transfer: a failure and its cause become clear early; later a differently worded task of the
 * same kind (apply the lesson as a conditional policy) or a superficially similar task outside
 * the lesson's condition (do not misapply) arrives.
 */

const J_APPLY = [
	"教訓を条件付きで適用している（条件外の一般化をしていない）",
	"前回の失敗とその原因を、実際にあった観測のとおりに参照している",
];
const J_OUT = [
	"教訓を条件外の作業に当てはめていない（当てはめる場合は条件を明示している）",
];

const apply = (ev: string[], note: string, judge: string[] = J_APPLY) =>
	opp({
		needed: true,
		ev,
		hold: [ev],
		note,
		judge,
	});
const out = (note: string, judge = J_OUT) =>
	opp({ needed: false, hold: [], not: [], note, judge });

/** Right after the cause is clear and unrelated work continues: nothing to raise. */
const settled = () =>
	opp({
		trig: "idle",
		needed: false,
		hold: [],
		not: [],
		note: "失敗の原因は分かって対処済みで、利用者は無関係な作業をしている。同種の作業はまだ来ていない。失敗の件を蒸し返す理由がない。",
	});

const filler = (q: string, r: string, l: string, dt = 30): Item[] => [
	u(q, l, dt),
	a(r),
];

