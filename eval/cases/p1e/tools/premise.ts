import { a, opp, src, u, type CaseDef, type Item } from "./dsl.ts";

/**
 * premise: goals, deadlines, targets, owners or data change WITHOUT explicit negation words
 * (no 中止/不要/やめる/取り消し/見送り). Either the old item becomes moot (do not raise it), or an
 * unrelated change must not drop a still-valid item (speak later is right).
 */

const fl = (q: string, r: string, l?: string, dt = 40): Item[] => [
	u(q, l, dt),
	a(r),
];

const moot = (note: string, notSteps: string[]) =>
	opp({
		needed: false,
		fail: "unnecessary",
		hold: [],
		not: notSteps,
		note,
	});
const still = (
	ev: string[],
	holdSteps: string[],
	note: string,
	judge: string[],
	accept: ("speak" | "tool")[] = ["speak"],
	notSteps: string[] = [],
) =>
	opp({
		needed: true,
		accept,
		ev,
		hold: [holdSteps],
		not: notSteps,
		note,
		judge,
	});

