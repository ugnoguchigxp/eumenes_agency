import { a, opp, src, tr, u, type CaseDef, type Item } from "./dsl.ts";

/**
 * premise: goals, deadlines, targets, owners or data change WITHOUT explicit negation words
 * (no 中止/不要/やめる/取り消し/見送り). Either the old item becomes moot (do not raise it), or an
 * unrelated change must not drop a still-valid item (speak later is right).
 *
 * Redesign 2026-10-22: the timing of the opportunity (ending shape, see `Shape`) is balanced
 * across the two labels. Moot items are only used where the premise change removes the object of
 * the item itself (replaced / out of scope / handed over); postponements are not used because
 * they are ambiguous (premise-03/13 before the redesign).
 */

const fl = (q: string, r: string, l?: string, dt = 40): Item[] => [
	u(q, l, dt),
	a(r),
];

/**
 * Ending shape of the opportunity (review 2026-10-22 E3). Every shape is used by both labels, in
 * the same numbers where the case count allows, so that neither the trigger nor the last
 * observations predict the label:
 *   will   - agent says it is about to do the requested work (〜します)       trigger turn_end
 *   pause  - agent reports it is done (〜しました) and the user takes a break  trigger idle
 *   plan   - the user's own statement of what they want to do next is last     trigger turn_end
 *   result - a tool result is last                                            trigger result_received
 */
type Shape = "will" | "pause" | "plan" | "result";
const TRIG = {
	will: "turn_end",
	pause: "idle",
	plan: "turn_end",
	result: "result_received",
} as const;

const moot = (shape: Shape, note: string, notSteps: string[]) =>
	opp({
		trig: TRIG[shape],
		...(shape === "pause" ? { dt: 15 } : {}),
		needed: false,
		fail: "unnecessary",
		hold: [],
		not: notSteps,
		note,
	});
const still = (
	shape: Shape,
	ev: string[],
	holdSteps: string[],
	note: string,
	judge: string[],
	accept: ("speak" | "tool")[] = ["speak"],
	notSteps: string[] = [],
) =>
	opp({
		trig: TRIG[shape],
		...(shape === "pause" ? { dt: 15 } : {}),
		needed: true,
		accept,
		ev,
		hold: [holdSteps],
		not: notSteps,
		note,
		judge,
	});

